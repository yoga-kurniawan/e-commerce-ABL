CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    cart_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    shipping_address TEXT,
    CONSTRAINT orders_status_valid CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED')),
    CONSTRAINT orders_shipping_address_not_blank CHECK (shipping_address IS NULL OR btrim(shipping_address) <> '')
);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL,
    product_name TEXT NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC NOT NULL,
    CONSTRAINT order_items_quantity_positive CHECK (quantity >= 1),
    CONSTRAINT order_items_unit_price_non_negative CHECK (unit_price >= 0 AND unit_price != 'NaN'::numeric),
    CONSTRAINT uq_order_items_order_product UNIQUE (order_id, product_id)
);

CREATE INDEX idx_orders_customer_id ON orders(customer_id);
CREATE INDEX idx_order_items_order_id ON order_items(order_id);
